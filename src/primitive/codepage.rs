    #[test]
    fn test_text() {
        let decoded = from_page::<Cp1142>(&(0u8..=255).collect::<Vec<_>>()).unwrap();
        assert_eq!(decoded.chars().count(), 256);
        for (wire, ch) in [
            (0x40, ' '),
            (0x4A, '#'),
            (0x4F, '!'),
            (0x5A, '€'),
            (0x5B, 'Å'),
            (0x6A, 'ø'),
            (0x7B, 'Æ'),
            (0xC0, 'æ'),
        ] {
            assert_eq!(decoded.chars().nth(wire), Some(ch));
        }
        let text = "ABCÆØÅæøå€[]{}|\\@#$";
        let wire = [
            0xC1, 0xC2, 0xC3, 0x7B, 0x7C, 0x5B, 0xC0, 0x6A, 0xD0, 0x5A, 0x9E, 0x9F, 0x9C, 0x47, 0xBB, 0xE0, 0x80, 0x4A, 0x67,
        ];
        assert_eq!(to_page::<Cp1142>(text), Ok(wire.to_vec()));
        assert_eq!(from_page::<Cp1142>(&wire), Ok(text.to_owned()));
        assert_eq!(to_page::<Cp1142>(&decoded), Ok((0u8..=255).collect()));
        for invalid in ["emoji: 😀", "¤", "\u{FFFF}"] {
            assert_eq!(to_page::<Cp1142>(invalid), Err(Error::Invalid));
        }
        assert_eq!(to_page::<Cp1140>("€é["), Ok(vec![0x9F, 0x51, 0xBA]));
        assert_eq!(to_page::<Cp273>("€"), Err(Error::Invalid));
        assert_eq!(to_page::<Cp850>("é─A"), Ok(vec![0x82, 0xC4, b'A']));
        assert_eq!(from_page::<Cp850>(b"\x82\xC4A"), Ok("é─A".to_owned()));
        assert_eq!(to_page::<Latin1>("é"), Ok(vec![0xE9]));
        assert_eq!(to_page::<Latin1>("€"), Err(Error::Invalid));
        assert_eq!(to_page::<Iso646Fi>("ÄÖÅäöå"), Ok(b"[\\]{|}".to_vec()));
        assert_eq!(from_page::<Iso646Fi>(b"[A"), Ok("ÄA".to_owned()));
        assert_eq!(to_page::<Iso646Fi>("$"), Err(Error::Invalid));
        assert_eq!(from_page::<Iso646Fi>(b"A\x80"), Err(Error::Invalid));
    }

    #[test]
    fn test_translation_boundaries() {
        let table = Cp037::ASCII_TO_PAGE;
        let mut out = [0xA5; 4];
        assert_eq!(translate_bytes(&mut out, b"", table), Ok(()));
        assert_eq!(out, [0xA5; 4]);
        assert_eq!(translate_bytes(&mut [], b"A", table), Err(Error::BufferOverflow));
        assert_eq!(translate_bytes(&mut out[..1], b"AB", table), Err(Error::BufferOverflow));
        assert_eq!(out, [0xA5; 4]);
        assert_eq!(translate_bytes(&mut out, b"AB", table), Ok(()));
        assert_eq!(out, [0xC1, 0xC2, 0xA5, 0xA5]);
        assert_eq!(decode_ascii_subset::<Cp037>(&mut out[..1], b"\xC1\xC2"), Err(Error::BufferOverflow));
    }

    #[test]
    fn test_encode_boundaries() {
        for (input, capacity, expected) in [
            (b"".as_slice(), 0, Ok(b"".as_slice())),
            (b"AB", 1, Err(Error::BufferOverflow)),
            (b"AB", 3, Ok(b"\xC1\xC2")),
            ("€".as_bytes(), 0, Err(Error::BufferOverflow)),
            ("€".as_bytes(), 1, Ok(b"\x5A")),
            ("Æ€".as_bytes(), 3, Ok(b"\x7B\x5A")),
            ("A¤".as_bytes(), 3, Err(Error::Invalid)),
            (b"A\xFF", 3, Err(Error::Invalid)),
        ] {
            let mut storage = [0xA5; 8];
            let mut output = &mut storage[..capacity];
            assert_eq!(
                encode_text::<Cp1142>(&mut output, input).map(|b| b.to_vec()),
                expected.map(|b| b.to_vec())
            );
            assert_eq!(output.len(), capacity - expected.map_or(0, |b| b.len()));
            assert!(output.iter().all(|&b| b == 0xA5));
            assert!(storage[capacity..].iter().all(|&b| b == 0xA5));
        }
        assert_eq!(encode_text::<Latin1>(&mut &mut [0; 1][..], b"AB"), Err(Error::BufferOverflow));
    }

