//! Single-byte code pages.
//!
//! A [`CodePage`] is its decode table, the Unicode code point of each byte;
//! every other table derives from it at compile time. Pages convert in two
//! ways:
//!
//! - The ASCII subset ([`encode_ascii_subset`], [`decode_ascii_subset`]) maps
//!   each ASCII byte to its page byte and back. It never fails: encoding
//!   replaces bytes outside the shared repertoire with the page's SUB, and
//!   decoding replaces them with ASCII SUB, like a lossy UTF-8 conversion. Use
//!   it for every field not expected to hold characters outside ASCII, and
//!   validate first when a field must be strict.
//! - Text ([`encode_text`], [`decode_text`]) converts between UTF-8 and the
//!   whole page, rejecting what the other side cannot represent, with an ASCII
//!   fast path and a cold path for everything else.
//!
//! All pages share this table-driven code. A Latin-1 indexed reverse table
//! covers every character below U+0100, and a sorted table holds the few above
//! it, such as the euro sign; for a page with one such character the search is
//! a single comparison.

#[cfg(all(not(debug_assertions), feature = "no-panic"))]
use no_panic::no_panic;

use crate::Error;
use crate::primitive::bytes::{copy_bytes, reserve_bytes};
use crate::utils::cold_path;

/// A [`CodePage::DECODE`] entry for a byte without a character.
pub const UNMAPPED: u16 = 0xFFFF;

/// A single-byte code page, defined by the character of each byte. A page
/// must map some byte to U+001A (SUB), which the ASCII subset substitutes.
pub trait CodePage {
    /// The Unicode code point of each byte, or [`UNMAPPED`]. Code points must
    /// be below U+10000, and no two bytes may share one.
    const DECODE: [u16; 256];
}

/// Tables derived from a page's decode table.
pub(crate) trait Tables: CodePage {
    /// The page byte decoding to U+001A.
    const SUB: u8 = sub_byte(&Self::DECODE);
    /// ASCII byte to page byte; anything else becomes [`Tables::SUB`].
    const ASCII_TO_PAGE: &'static [u8; 256] = &ascii_to_page(&Self::DECODE, Self::SUB);
    /// Page byte to ASCII byte; anything else becomes 0x80.
    const PAGE_TO_ASCII: &'static [u8; 256] = &page_to_ascii(&Self::DECODE, 0x80);
    /// Page byte to ASCII byte; anything else becomes ASCII SUB.
    const PAGE_TO_ASCII_LOSSY: &'static [u8; 256] = &page_to_ascii(&Self::DECODE, 0x1A);
    /// Page byte of each Latin-1 code point, or [`UNMAPPED`].
    const LATIN1_TO_PAGE: &'static [u16; 256] = &latin1_to_page(&Self::DECODE);
    /// Characters above U+00FF as `code << 8 | byte`, sorted, in the first
    /// [`Tables::HIGH_LEN`] entries.
    const HIGH: &'static [u32; 256] = &high_chars(&Self::DECODE);
    const HIGH_LEN: usize = high_len(&Self::DECODE);
    /// Whether every ASCII character has a page byte.
    const ASCII_COMPLETE: bool = ascii_complete(&Self::DECODE);
    /// Whether every byte below 0x80 decodes to itself.
    const ASCII_IDENTITY: bool = ascii_identity(&Self::DECODE);
}

impl<P: CodePage> Tables for P {}

const fn sub_byte(decode: &[u16; 256]) -> u8 {
    let mut i = 0;
    while i < 256 {
        if decode[i] == 0x1A {
            return i as u8;
        }
        i += 1;
    }
    panic!("a code page must map a byte to U+001A")
}

const fn ascii_to_page(decode: &[u16; 256], sub: u8) -> [u8; 256] {
    let mut table = [sub; 256];
    let mut i = 0;
    while i < 256 {
        if decode[i] < 0x80 {
            table[decode[i] as usize] = i as u8;
        }
        i += 1;
    }
    table
}

const fn page_to_ascii(decode: &[u16; 256], other: u8) -> [u8; 256] {
    let mut table = [other; 256];
    let mut i = 0;
    while i < 256 {
        if decode[i] < 0x80 {
            table[i] = decode[i] as u8;
        }
        i += 1;
    }
    table
}

const fn latin1_to_page(decode: &[u16; 256]) -> [u16; 256] {
    let mut table = [UNMAPPED; 256];
    let mut i = 0;
    while i < 256 {
        if decode[i] < 0x100 {
            assert!(
                table[decode[i] as usize] == UNMAPPED,
                "a code page must not map two bytes to one character"
            );
            table[decode[i] as usize] = i as u16;
        }
        i += 1;
    }
    table
}

const fn high_len(decode: &[u16; 256]) -> usize {
    let mut len = 0;
    let mut i = 0;
    while i < 256 {
        if decode[i] > 0xFF && decode[i] != UNMAPPED {
            len += 1;
        }
        i += 1;
    }
    len
}

const fn high_chars(decode: &[u16; 256]) -> [u32; 256] {
    let mut table = [u32::MAX; 256];
    let mut len = 0;
    let mut i = 0;
    while i < 256 {
        if decode[i] > 0xFF && decode[i] != UNMAPPED {
            // Insertion sort by code point.
            let entry = (decode[i] as u32) << 8 | i as u32;
            let mut j = len;
            while j > 0 && table[j - 1] > entry {
                table[j] = table[j - 1];
                j -= 1;
            }
            table[j] = entry;
            len += 1;
        }
        i += 1;
    }
    table
}

const fn ascii_complete(decode: &[u16; 256]) -> bool {
    let table = latin1_to_page(decode);
    let mut i = 0;
    while i < 0x80 {
        if table[i] == UNMAPPED {
            return false;
        }
        i += 1;
    }
    true
}

const fn ascii_identity(decode: &[u16; 256]) -> bool {
    let mut i = 0;
    while i < 0x80 {
        if decode[i] != i as u16 {
            return false;
        }
        i += 1;
    }
    true
}

/// Translates bytes through a 256-entry lookup table, writing to `output`.
/// A short output returns `BufferOverflow` without writing. Any output suffix
/// beyond the input length is left unchanged.
#[inline(always)]
#[cfg_attr(all(not(debug_assertions), feature = "no-panic"), no_panic)]
pub fn translate_bytes(output: &mut [u8], input: &[u8], table: &[u8; 256]) -> Result<(), Error> {
    let output = output.get_mut(..input.len()).ok_or_else(|| {
        cold_path();
        Error::BufferOverflow
    })?;
    for (o, i) in output.iter_mut().zip(input) {
        *o = table[*i as usize];
    }
    Ok(())
}

/// Translates bytes through a 256-entry lookup table in place.
#[inline(always)]
#[cfg_attr(all(not(debug_assertions), feature = "no-panic"), no_panic)]
pub fn translate_bytes_inplace(buf: &mut [u8], table: &[u8; 256]) {
    for b in buf {
        *b = table[*b as usize];
    }
}

/// Encode ASCII bytes as page `P` in place, byte for byte. Bytes outside the
/// ASCII characters of the page become the page's SUB. This maps bytes and
/// does not decode UTF-8.
#[inline(always)]
#[cfg_attr(all(not(debug_assertions), feature = "no-panic"), no_panic)]
pub fn encode_ascii_subset<P: CodePage>(buf: &mut [u8]) {
    translate_bytes_inplace(buf, P::ASCII_TO_PAGE);
}

/// Decode page `P` bytes as ASCII, byte for byte, writing to `output`. Bytes
/// whose characters are not ASCII become ASCII SUB (0x1A), and so does the
/// page's own SUB. A short output returns `BufferOverflow` without writing.
#[inline(always)]
#[cfg_attr(all(not(debug_assertions), feature = "no-panic"), no_panic)]
pub fn decode_ascii_subset<P: CodePage>(output: &mut [u8], input: &[u8]) -> Result<(), Error> {
    translate_bytes(output, input, P::PAGE_TO_ASCII_LOSSY)
}

/// Whether a page `P` byte decodes to an ASCII character, so that
/// [`decode_ascii_subset`] keeps it.
#[inline(always)]
#[cfg_attr(all(not(debug_assertions), feature = "no-panic"), no_panic)]
pub fn is_ascii_subset_byte<P: CodePage>(byte: u8) -> bool {
    P::PAGE_TO_ASCII[byte as usize] < 0x80
}

/// The page `P` byte of a character, if the page has one.
#[inline(always)]
#[cfg_attr(all(not(debug_assertions), feature = "no-panic"), no_panic)]
pub fn encode_char<P: CodePage>(ch: char) -> Option<u8> {
    let code = u32::from(ch);
    if let Some(&byte) = P::LATIN1_TO_PAGE.get(code as usize) {
        return (byte != UNMAPPED).then_some(byte as u8);
    }
    let high = P::HIGH.get(..P::HIGH_LEN).unwrap_or_default();
    high.binary_search_by(|entry| (entry >> 8).cmp(&code))
        .ok()
        .and_then(|index| high.get(index))
        .map(|entry| *entry as u8)
}

/// Encode UTF-8 bytes as page `P`, rejecting invalid UTF-8 and unrepresentable
/// characters.
#[inline(always)]
#[cfg_attr(all(not(debug_assertions), feature = "no-panic"), no_panic)]
pub fn encode_text<'a, P: CodePage>(output: &mut &'a mut [u8], input: &[u8]) -> Result<&'a mut [u8], Error> {
    if P::ASCII_COMPLETE && input.is_ascii() {
        if P::ASCII_IDENTITY {
            return copy_bytes(output, input);
        }
        let buf = reserve_bytes(output, input.len())?;
        translate_bytes(buf, input, P::ASCII_TO_PAGE)?;
        return Ok(buf);
    }

    encode_text_slow::<P>(output, input)
}

/// Decode page `P` bytes into UTF-8, rejecting unmapped bytes.
#[inline(always)]
#[cfg_attr(all(not(debug_assertions), feature = "no-panic"), no_panic)]
pub fn decode_text<'a, P: CodePage>(output: &mut &'a mut [u8], input: &[u8]) -> Result<&'a mut [u8], Error> {
    if P::ASCII_IDENTITY {
        if input.is_ascii() {
            return copy_bytes(output, input);
        }
    } else if input.iter().all(|&byte| P::PAGE_TO_ASCII[byte as usize] < 0x80) {
        let buf = reserve_bytes(output, input.len())?;
        translate_bytes(buf, input, P::PAGE_TO_ASCII)?;
        return Ok(buf);
    }

    decode_text_slow::<P>(output, input)
}

#[cold]
#[inline(never)]
fn encode_text_slow<'a, P: CodePage>(output: &mut &'a mut [u8], input: &[u8]) -> Result<&'a mut [u8], Error> {
    let text = core::str::from_utf8(input).map_err(|_| {
        cold_path();
        Error::Invalid
    })?;
    let mut char_len = 0usize;
    for ch in text.chars() {
        if encode_char::<P>(ch).is_none() {
            cold_path();
            return Err(Error::Invalid);
        }
        char_len += 1;
    }
    let buf = reserve_bytes(output, char_len)?;
    for (dst, ch) in buf.iter_mut().zip(text.chars()) {
        *dst = encode_char::<P>(ch).ok_or_else(|| {
            cold_path();
            Error::Invalid
        })?;
    }
    Ok(buf)
}

#[cold]
#[inline(never)]
fn decode_text_slow<'a, P: CodePage>(output: &mut &'a mut [u8], input: &[u8]) -> Result<&'a mut [u8], Error> {
    let mut used = 0usize;
    for &byte in input {
        let code = P::DECODE[byte as usize];
        let ch = char::from_u32(u32::from(code)).filter(|_| code != UNMAPPED).ok_or_else(|| {
            cold_path();
            Error::Invalid
        })?;
        let mut utf8 = [0u8; 4];
        let encoded = ch.encode_utf8(&mut utf8).as_bytes();
        let end = used.checked_add(encoded.len()).ok_or_else(|| {
            cold_path();
            Error::BufferOverflow
        })?;
        let buf = output.get_mut(used..end).ok_or_else(|| {
            cold_path();
            Error::BufferOverflow
        })?;
        buf.copy_from_slice(encoded);
        used = end;
    }
    reserve_bytes(output, used)
}

